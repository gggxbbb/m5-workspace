import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_HEADER = ROOT / "lib" / "MotdUi" / "src" / "MotdFonts.h"

FONTS = [
    {
        "name": "kFontMeta10",
        "ttf": r"C:\Windows\Fonts\segoeuib.ttf",
        "size": 10,
        "range": "0x20-0x7E,0xB0",
    },
    {
        "name": "kFontTitle14",
        "ttf": r"C:\Windows\Fonts\segoeuib.ttf",
        "size": 13,
        "range": "0x20-0x7E,0xB0",
    },
    {
        "name": "kFontNum18",
        "ttf": r"C:\Windows\Fonts\consolab.ttf",
        "size": 16,
        "range": "0x20-0x7E",
    },
]


def run_lv_font_conv(spec: dict, out_bin: Path) -> bytes:
    cmd = [
        "npx.cmd" if os.name == "nt" else "npx",
        "--yes",
        "lv_font_conv",
        "--font", spec["ttf"],
        "--size", str(spec["size"]),
        "--bpp", "4",
        "--format", "bin",
        "--no-compress",
        "--no-kerning",
        "--range", spec["range"],
        "-o", str(out_bin),
    ]
    res = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if res.returncode != 0:
        raise RuntimeError(f"lv_font_conv failed for {spec['name']}:\n{res.stdout}\n{res.stderr}")
    data = out_bin.read_bytes()
    if len(data) < 16 or data[4:8] != b"head":
        raise RuntimeError(f"Invalid BFF header in {spec['name']} (bytes[4:8]={data[4:8]!r})")
    return data


def format_array(name: str, data: bytes) -> str:
    lines = [f"constexpr size_t {name}Size = {len(data)};", f"constexpr uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i : i + 16])
        comma = "," if i + 16 < len(data) else ""
        lines.append(f"  {chunk}{comma}")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    OUT_HEADER.parent.mkdir(parents=True, exist_ok=True)
    parts = [
        "// Auto-generated by tools/gen_fonts.py via lv_font_conv (4-bpp uncompressed BFF for M5GFX ft_lvgl).",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace motd::fonts {",
        "",
    ]
    total = 0
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        for spec in FONTS:
            data = run_lv_font_conv(spec, tmp_dir / f"{spec['name']}.bin")
            total += len(data)
            print(f"{spec['name']}: {len(data)} bytes (ttf={Path(spec['ttf']).name}, size={spec['size']})")
            parts.append(format_array(spec["name"], data))
            parts.append("")
    parts.append("}  // namespace motd::fonts")
    parts.append("")
    OUT_HEADER.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT_HEADER} (total font payload: {total} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
